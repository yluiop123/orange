package http

// Documentation endpoints are generated from the Go annotations in this
// package (see cmd/server/main.go for the general metadata). Both routes are
// mounted on the root router, outside the /api/v1 group and outside
// requireAuth, so they are anonymous.

import (
	"net/http"

	"github.com/gin-gonic/gin"
	"github.com/swaggo/files"
	"github.com/swaggo/gin-swagger"

	"github.com/orange/backend-go-gin-gorm/docs"
)

// registerSwaggerRoutes mounts the anonymous documentation endpoints:
//
//	GET /swagger          Swagger UI (also /swagger/*any for its assets)
//	GET /openapi.json     Swagger 2.0 document generated by swag
func registerSwaggerRoutes(router *gin.Engine) {
	swaggerUI := ginSwagger.CustomWrapHandler(&ginSwagger.Config{
		URL:                  "/openapi.json",
		Title:                "Orange API",
		DocExpansion:         "none",
		PersistAuthorization: true,
	}, swaggerFiles.Handler)

	router.GET("/openapi.json", func(c *gin.Context) {
		c.Data(http.StatusOK, "application/json", []byte(docs.SwaggerInfo.ReadDoc()))
	})

	router.GET("/swagger", serveSwaggerIndex(swaggerUI))
	router.GET("/swagger/*any", swaggerUI)
}

// serveSwaggerIndex makes the bare /swagger path render the UI index without a
// redirect. gin-swagger only recognises explicit asset names (index.html,
// swagger-initializer.js, doc.json, ...), so the path is rewritten before it
// reaches the handler.
func serveSwaggerIndex(handler gin.HandlerFunc) gin.HandlerFunc {
	return func(c *gin.Context) {
		c.Request.URL.Path = "/swagger/index.html"
		c.Request.RequestURI = "/swagger/index.html"
		handler(c)
	}
}
