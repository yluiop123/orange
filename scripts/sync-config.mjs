import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sourcePath = path.join(root, "config/app.env");
const examplePath = path.join(root, "config/app.example.env");
const source = fs.existsSync(sourcePath) ? sourcePath : examplePath;

function parseEnv(file) {
  const values = {};
  for (const rawLine of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const index = line.indexOf("=");
    if (index === -1) continue;
    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

const env = parseEnv(source);
const need = (key, fallback = "") => env[key] ?? fallback;

function write(relativePath, content, commentPrefix = "#") {
  const target = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(
    target,
    `${commentPrefix} Generated by scripts/sync-config.mjs from ${path.relative(root, source)}.\n` +
      `${commentPrefix} Do not edit by hand; edit config/app.env and re-run the generator.\n\n` +
      content,
    "utf8",
  );
  console.log(`generated ${relativePath}`);
}

function dotenv(pairs) {
  return (
    Object.entries(pairs)
      .map(([key, value]) => `${key}=${value}`)
      .join("\n") + "\n"
  );
}

